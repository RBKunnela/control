package pyschema

import (
	"strings"
	"testing"
)

func smallModel() Model {
	return Model{
		Messages: []Message{
			{Name: "wire.test.Empty"},
			{Name: "wire.test.Whole", Members: []Member{
				{JSONName: "id", Number: 1, Kind: KindString, Shape: ShapeOne},
				{JSONName: "shades", Number: 2, Kind: KindEnum, Shape: ShapeList, TypeName: "wire.test.Colour"},
				{JSONName: "labels", Number: 3, Kind: KindString, Shape: ShapeMap},
			}},
		},
		Enums: []Enum{
			{Name: "wire.test.Colour", Values: []Value{{Name: "COLOUR_UNSPECIFIED", Number: 0}, {Name: "COLOUR_RED", Number: 7}}},
			{Name: "wire.test.Depth", Values: []Value{{Name: "DEPTH_UNSPECIFIED", Number: 0}}},
		},
	}
}

const smallTable = `# Generated by scripts/gen-pyschema.go from the compiled descriptors of api/proto.
# Do not edit: ` + "`make docs-gen`" + ` rewrites this file, and a test fails when the two differ.

# Each member of a message under its JSON name: (kind, shape, type name).
MESSAGES: dict[str, dict[str, tuple[str, str, str]]] = {
    "wire.test.Empty": {},
    "wire.test.Whole": {
        "id": ("string", "one", ""),
        "shades": ("enum", "list", "wire.test.Colour"),
        "labels": ("string", "map", ""),
    },
}
ENUMS: dict[str, dict[str, int]] = {
    "wire.test.Colour": {"COLOUR_UNSPECIFIED": 0, "COLOUR_RED": 7},
    "wire.test.Depth": {"DEPTH_UNSPECIFIED": 0},
}
`

func TestPythonWritesTheTable(t *testing.T) {
	got, err := Python(smallModel())
	if err != nil {
		t.Fatalf("Python: %v", err)
	}
	if string(got) != smallTable {
		t.Errorf("Python:\n got:\n%s\nwant:\n%s", got, smallTable)
	}
}

func TestPythonRefusesAModelWithNoMessage(t *testing.T) {
	m := smallModel()
	m.Messages = nil
	got, err := Python(m)
	const want = "the model holds no message; refusing to write an empty table"
	if err == nil || err.Error() != want {
		t.Errorf("Python: got %v, want %q", err, want)
	}
	if got != nil {
		t.Errorf("a refusal came with a table:\n%s", got)
	}
}

// A name is written between double quotes as it is, so one that would end
// the literal or need an escape is refused wherever the model carries it.
func TestPythonRefusesANameALiteralCannotCarry(t *testing.T) {
	cases := map[string]struct {
		plant func(*Model)
		want  string
	}{
		"a message name": {func(m *Model) { m.Messages[1].Name = `wire.test."Whole` }, `"wire.test.\"Whole" holds U+0022 at byte 10, which the table does not write`},
		"a JSON name":    {func(m *Model) { m.Messages[1].Members[0].JSONName = "i\\d" }, `wire.test.Whole: "i\\d" holds U+005C at byte 1, which the table does not write`},
		"a kind":         {func(m *Model) { m.Messages[1].Members[0].Kind = "str ing" }, `wire.test.Whole: "str ing" holds U+0020 at byte 3, which the table does not write`},
		"a shape":        {func(m *Model) { m.Messages[1].Members[0].Shape = "one\n" }, `wire.test.Whole: "one\n" holds U+000A at byte 3, which the table does not write`},
		"a type name":    {func(m *Model) { m.Messages[1].Members[1].TypeName = "wire.test.Colour#" }, `wire.test.Whole: "wire.test.Colour#" holds U+0023 at byte 16, which the table does not write`},
		"an enum name":   {func(m *Model) { m.Enums[0].Name = "wire.tést.Colour" }, `"wire.tést.Colour" holds U+00E9 at byte 6, which the table does not write`},
		"a value name":   {func(m *Model) { m.Enums[0].Values[1].Name = "COLOUR'RED" }, `wire.test.Colour: "COLOUR'RED" holds U+0027 at byte 6, which the table does not write`},
		"an empty name":  {func(m *Model) { m.Messages[0].Name = "" }, "an empty name"},
		"an empty kind":  {func(m *Model) { m.Messages[1].Members[2].Kind = "" }, "wire.test.Whole: an empty name"},
		"an empty value": {func(m *Model) { m.Enums[1].Values[0].Name = "" }, "wire.test.Depth: an empty name"},
	}
	for name, c := range cases {
		t.Run(name, func(t *testing.T) {
			m := smallModel()
			c.plant(&m)
			got, err := Python(m)
			if err == nil {
				t.Fatalf("Python wrote the name:\n%s", got)
			}
			if err.Error() != c.want {
				t.Errorf("refusal:\n got %q\nwant %q", err, c.want)
			}
		})
	}
}

// Only a message or an enum has a name to point at; every other kind leaves
// the third slot empty, and that is not a name to refuse.
func TestPythonWritesAnEmptyTypeName(t *testing.T) {
	got, err := Python(Model{Messages: []Message{{Name: "wire.test.One", Members: []Member{{JSONName: "id", Number: 1, Kind: KindString, Shape: ShapeOne}}}}})
	if err != nil {
		t.Fatalf("Python: %v", err)
	}
	const want = "    \"wire.test.One\": {\n        \"id\": (\"string\", \"one\", \"\"),\n    },\n}\nENUMS: dict[str, dict[str, int]] = {\n}\n"
	if !strings.HasSuffix(string(got), want) {
		t.Errorf("Python:\n got:\n%s\nwant it to end:\n%s", got, want)
	}
}
